const used = new Set<string>();
export const CATEGORIES: Category[] = RAW.map((c) => ({
  key: c.k, slug: c.slug, title: c.t, desc: c.d, about: c.about, serve: c.serve, finger: !!c.finger,
  items: c.items.map(([name, price, from, weight, img], i) => {
    let slug = translit(name);
    while (used.has(slug)) slug += '-2';
    used.add(slug);
    return { id: `${c.k}-${i}`, slug, name, price, from: !!from, weight, img: imgUrl(img), cat: c.k };
  }),
}));

export const PRODUCTS: Product[] = CATEGORIES.flatMap((c) => c.items);
export const BY_ID: Record<string, Product> = Object.fromEntries(PRODUCTS.map((p) => [p.id, p]));
export const BY_SLUG: Record<string, Product> = Object.fromEntries(PRODUCTS.map((p) => [p.slug, p]));
export const CAT: Record<CatKey, Category> = Object.fromEntries(CATEGORIES.map((c) => [c.key, c])) as Record<CatKey, Category>;
export const catBySlug = (slug?: string) => CATEGORIES.find((c) => c.slug === slug);

export const find = (k: CatKey, frag: string) => {
  const p = CAT[k].items.find((i) => i.name.includes(frag));
  if (!p) throw new Error(`Нет блюда «${frag}» в ${k}`);
  return p;
};

/** Короткое название для плашек: без пояснений в скобках */
export const shortName = (n: string) => n.replace(/\s*\(.*\)/, '');

/** Позиции, которые продаются поштучно и подходят для подноса */
export const isPiece = (p: Product) => p.weight === '1 шт' && CAT[p.cat].finger;

